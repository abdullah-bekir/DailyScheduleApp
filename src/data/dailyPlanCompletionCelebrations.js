const FALLBACK_LANGUAGE = 'en';
const SAFE_FALLBACK_LANGUAGE = 'tr';

export function getCelebrationPoolForGoal(planGoal, language = SAFE_FALLBACK_LANGUAGE) {
  const goal = Number(planGoal);
  const languagePool = PLAN_COMPLETION_CELEBRATIONS_BY_LANGUAGE[language]
    ?? PLAN_COMPLETION_CELEBRATIONS_BY_LANGUAGE[FALLBACK_LANGUAGE]
    ?? PLAN_COMPLETION_CELEBRATIONS_BY_LANGUAGE[SAFE_FALLBACK_LANGUAGE];
  return languagePool[goal]
    ?? PLAN_COMPLETION_CELEBRATIONS_BY_LANGUAGE[FALLBACK_LANGUAGE][goal]
    ?? PLAN_COMPLETION_CELEBRATIONS_BY_LANGUAGE[SAFE_FALLBACK_LANGUAGE][goal]
    ?? PLAN_COMPLETION_CELEBRATIONS_BY_LANGUAGE[FALLBACK_LANGUAGE][8];
}

export function pickCelebrationIndex(poolLength, avoidIdx) {
  if (poolLength <= 0) return 0;
  if (poolLength === 1) return 0;
  let n = Math.floor(Math.random() * poolLength);
  if (avoidIdx === undefined || poolLength <= 2) return n;
  let guard = 0;
  while (n === avoidIdx && guard < 24) {
    n = Math.floor(Math.random() * poolLength);
    guard += 1;
  }
  return n;
}
